  <h1 id="page-title" tabindex="-1">About Agent incidents</h1>
  <p class="lead">One timeline and a central place for curated information about AI agents showing unwanted behaviour.</p>

  <h2>Why this site exists</h2>
  <p>I want more transparency about what is happening with AI agents. Reports from labs, researchers and people using these systems are scattered across different places. Bringing them together makes it easier to follow what happened and find the original sources.</p>
  <p>This is an ongoing project. As new incidents and findings come out, I’ll update the timeline. Little by little, I hope we get a fuller picture of what is going on and can start connecting the dots between cases.</p>

  <h2 id="methodology">What goes into the timeline</h2>
  <p>There are plenty of claims about agent behaviour. I focus on cases with supporting evidence that people can check, including reports from the labs themselves. Each entry links to its sources and makes clear which parts are reported observations and which are interpretations.</p>
  <p>Cases from training, evaluations and everyday use are labelled by their setting. The timeline keeps the date of an incident separate from the dates of reports about it.</p>

  <h2>Who’s behind it</h2>
  <p>I’m <a href="https://jowimo.com/">Jonas</a>. I’ve come across a lot of interesting material while looking into agent behaviour, and this site grew out of that interest. It’s a hobby project that I run myself, with no external funding or organisation behind it. I aim to apply the same standards to every lab and follow the evidence as it develops.</p>

  <h2>Help improve it</h2>
  <p>If something is wrong, or you have another case or source to add, <a href="/submit/">get in touch</a>. I’ll look into it and update the entry or add the new information when the evidence supports it.</p>
  <p>The <a href="/roadmap/">roadmap</a> sets out what I’d like to build next and what each step needs. Contributions are welcome.</p>
